// Завдання 4.7. Обчислення суми ряду Тейлора за допомогою
// ітераційних циклів та рекурентних співвідношень. Варіант 18
//
//         inf  (-1)^n * (x-1)^(n+1)             (x-1)^2   (x-1)^3
// ln x =  SUM  --------------------  = (x-1) - ------- + ------- - ...
//         n=0         n + 1                       2         3
//
// область збіжності: 0 < x <= 2
// перший доданок:       a0 = x - 1
// коеф. рекурентності:  R = a(n) / a(n-1) = -(x - 1) * n / (n + 1)

#include <iostream>
#include <iomanip>
#include <cmath>

using namespace std;

int main()
{
    double xp, xk, dx;  // початок, кінець інтервалу та крок табуляції
    double eps;         // точність обчислення суми ряду
    double x;           // поточне значення аргументу
    double a;           // поточний доданок ряду
    double R;           // коефіцієнт рекурентності
    double S;           // сума ряду
    int n;              // номер доданка

    cout << "xp = "; cin >> xp;
    cout << "xk = "; cin >> xk;
    cout << "dx = "; cin >> dx;
    cout << "eps = "; cin >> eps;

    // заголовок і шапка таблиці
    cout << fixed;
    cout << endl << "        Taylor series for ln(x)" << endl;
    cout << "-------------------------------------------------" << endl;
    cout << "|" << setw(6) << "x" << "     |"
        << setw(9) << "ln(x)" << "    |"
        << setw(8) << "S" << "     |"
        << setw(6) << "n" << "   |" << endl;
    cout << "-------------------------------------------------" << endl;

    // табуляція функції
    x = xp;
    while (x <= xk)
    {
        n = 0;
        a = x - 1;          // перший доданок
        S = a;
        do
        {
            n++;
            R = -(x - 1) * n / (n + 1);
            a *= R;         // наступний доданок через попередній
            S += a;
        } while (abs(a) >= eps);

        cout << "|" << setw(8) << setprecision(2) << x << "   |"
            << setw(10) << setprecision(5) << log(x) << "   |"
            << setw(10) << setprecision(5) << S << "   |"
            << setw(6) << n << "   |" << endl;

        x += dx;
    }
    cout << "-------------------------------------------------" << endl;

    return 0;
}
